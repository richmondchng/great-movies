CREATE TABLE file_upload (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artifact_type VARCHAR(50) NOT NULL,
    artifact_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAM,
    created_by VARCHAR(50)
);

CREATE TABLE file_upload_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_upload_id BIGINT NOT NULL,
    file_upload_type VARCHAR(50) NOT NULL,
    file_path VARCHAR(50),
    file_name VARCHAR(50),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAM,
    created_by VARCHAR(50),

    CONSTRAINT fk_file_upload_items_file_upload
        FOREIGN KEY (file_upload_id)
            REFERENCES file_upload (id)
            ON DELETE CASCADE
);